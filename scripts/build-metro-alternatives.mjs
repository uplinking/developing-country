// OSM main roads
async function fetchRoadsOverpass() {
  const query = `[out:json][timeout:170];way["highway"~"^(${ROAD_CLASSES.join('|')})$"](${STUDY_BBOX.s},${STUDY_BBOX.w},${STUDY_BBOX.n},${STUDY_BBOX.e});out geom;`
  let lastErr
  for (let attempt = 0; attempt < 2; attempt++) {
    for (const endpoint of OVERPASS) {
      try {
        const res = await fetch(endpoint, {
          method: 'POST',
          headers: { 'Content-Type': 'application/x-www-form-urlencoded', Accept: 'application/json', 'User-Agent': UA },
          body: `data=${encodeURIComponent(query)}`,
          signal: AbortSignal.timeout(200_000),
        })
        if (!res.ok) throw new Error(`HTTP ${res.status}`)
        const json = await res.json()
        const ways = (json.elements ?? [])
          .filter((el) => el.type === 'way' && Array.isArray(el.geometry))
          .map((el) => ({
            id: el.id,
            highway: String(el.tags?.highway ?? ''),
            name: typeof el.tags?.name === 'string' ? el.tags.name : null,
            coords: el.geometry.map((p) => [Number(p.lon), Number(p.lat)]),
          }))
        return { via: `Overpass ${endpoint}`, osm_base: json.osm3s?.timestamp_osm_base ?? null, ways }
      } catch (e) {
        lastErr = e
        console.warn(`  overpass ${endpoint}: ${e.message}`)
      }
    }
  }
  throw lastErr ?? new Error('overpass failed')
}

function fetchRoadsOsmium(pbf) {
  const tmp = join(ROOT, 'data/src/osm')
  mkdirSync(tmp, { recursive: true })
  const clip = join(tmp, '_bbox.osm.pbf')
  const roads = join(tmp, '_roads.osm.pbf')
  const out = join(tmp, '_roads.geojsonseq')
  const run = (args) => {
    const p = Bun.spawnSync(['osmium', ...args])
    if (p.exitCode !== 0) throw new Error(`osmium ${args[0]} failed: ${new TextDecoder().decode(p.stderr)}`)
  }
  run(['extract', '-b', `${STUDY_BBOX.w},${STUDY_BBOX.s},${STUDY_BBOX.e},${STUDY_BBOX.n}`, pbf, '-o', clip, '--overwrite'])
  run(['tags-filter', clip, ...ROAD_CLASSES.map((c) => `w/highway=${c}`), '-o', roads, '--overwrite'])
  run(['export', roads, '-f', 'geojsonseq', '--geometry-types=linestring', '-o', out, '--overwrite'])
  const ways = readFileSync(out, 'utf8')
    .split('\n')
    .map((l) => l.replace(/^\x1e/, '').trim())
    .filter(Boolean)
    .map((l, k) => {
      const f = JSON.parse(l)
      return { id: k, highway: String(f.properties?.highway ?? ''), name: f.properties?.name ?? null, coords: f.geometry.coordinates }
    })
  return { via: `osmium extract of ${pbf}`, osm_base: null, ways }
}

async function loadRoads() {
  if (existsSync(ROADS_CACHE)) return JSON.parse(readFileSync(ROADS_CACHE, 'utf8'))
  let data
  try {
    data = await fetchRoadsOverpass()
  } catch (e) {
    if (!process.env.OSM_PBF) throw new Error(`Overpass failed (${e.message}); set OSM_PBF to a Geofabrik Sri Lanka extract to use osmium`)
    data = fetchRoadsOsmium(process.env.OSM_PBF)
  }
  const ways = data.ways
    .filter((w) => ROAD_CLASSES.includes(w.highway) && w.coords.length >= 2)
    .filter((w) => w.coords.every(([x, y]) => Number.isFinite(x) && Number.isFinite(y)))
    .map((w) => ({ ...w, coords: w.coords.map(([x, y]) => [round(x, 7), round(y, 7)]) }))
    .sort((a, b) => a.id - b.id)
  if (ways.length < 1000) throw new Error(`only ${ways.length} main-road ways — fetch looks truncated`)
  const cache = { source: 'OpenStreetMap contributors (ODbL)', via: data.via, osm_base: data.osm_base, classes: ROAD_CLASSES, bbox: STUDY_BBOX, ways }
  mkdirSync(join(ROOT, 'data/src/osm'), { recursive: true })
  writeFileSync(ROADS_CACHE, JSON.stringify(cache))
  return cache
}

/** Main roads → packed graph understood by buildGraph (metre weights, ≥ 0.1 m). */
export function roadGraph(ways) {
  const index = new Map()
  const nodes = []
  const edges = []
  const seen = new Set()
  const nid = ([lng, lat]) => {
    const key = `${lng},${lat}`
    let i = index.get(key)
    if (i === undefined) {
      i = nodes.length / 2
      nodes.push(lng, lat)
      index.set(key, i)
    }
    return i
  }
  for (const w of ways) {
    for (let k = 1; k < w.coords.length; k++) {
      const a = nid(w.coords[k - 1])
      const b = nid(w.coords[k])
      if (a === b) continue
      const key = a < b ? `${a}|${b}` : `${b}|${a}`
      if (seen.has(key)) continue
      seen.add(key)
      const [ax, ay] = project(...w.coords[k - 1])
      const [bx, by] = project(...w.coords[k])
      const m = Math.max(0.1, round(Math.hypot(bx - ax, by - ay), 1))
      edges.push(a, b, m)
    }
  }
  return buildGraph({ packed: true, nodes, edges, bbox: [STUDY_BBOX.w, STUDY_BBOX.s, STUDY_BBOX.e, STUDY_BBOX.n] })
}

/** Shortest road path between two snapped points: { metres, points: [[x,y]…] } in metres. */
export function roadPath(rg, from, to) {
  const lerp = (e, t) => [rg.x[rg.ea[e]] + (rg.x[rg.eb[e]] - rg.x[rg.ea[e]]) * t, rg.y[rg.ea[e]] + (rg.y[rg.eb[e]] - rg.y[rg.ea[e]]) * t]
  if (from.edge === to.edge) {
    const w = rg.ew[from.edge]
    return { metres: from.perp + Math.abs(from.t - to.t) * w + to.perp, points: [[from.x, from.y], lerp(from.edge, from.t), lerp(to.edge, to.t), [to.x, to.y]] }
  }
  const dist = new Float64Array(rg.n).fill(Infinity)
  const prev = new Int32Array(rg.n).fill(-1)
  const heap = [] // simple binary heap of [d, node]
  const push = (d, v) => {
    heap.push([d, v])
    let i = heap.length - 1
    while (i > 0) {
      const p = (i - 1) >> 1
      if (heap[p][0] < heap[i][0] || (heap[p][0] === heap[i][0] && heap[p][1] <= heap[i][1])) break
      ;[heap[p], heap[i]] = [heap[i], heap[p]]
      i = p
    }
  }
  const pop = () => {
    const top = heap[0]
    const last = heap.pop()
    if (heap.length) {
      heap[0] = last
      let i = 0
      for (;;) {
        const l = 2 * i + 1
        const r = l + 1
        let s = i
        const less = (a, b) => heap[a][0] < heap[b][0] || (heap[a][0] === heap[b][0] && heap[a][1] < heap[b][1])
        if (l < heap.length && less(l, s)) s = l
        if (r < heap.length && less(r, s)) s = r
        if (s === i) break
        ;[heap[s], heap[i]] = [heap[i], heap[s]]
        i = s
      }
    }
    return top
  }
  const wf = rg.ew[from.edge]
  dist[rg.ea[from.edge]] = from.t * wf
  dist[rg.eb[from.edge]] = (1 - from.t) * wf
  push(dist[rg.ea[from.edge]], rg.ea[from.edge])
  push(dist[rg.eb[from.edge]], rg.eb[from.edge])
  const ta = rg.ea[to.edge]
  const tb = rg.eb[to.edge]
  while (heap.length) {
    const [d, u] = pop()
    if (d > dist[u]) continue
    if (u === ta && dist[tb] <= d) break
    if (u === tb && dist[ta] <= d) break
    for (let k = rg.off[u]; k < rg.off[u + 1]; k++) {
      const v = rg.adjNode[k]
      const nd = d + rg.ew[rg.adjEdge[k]]
      if (nd < dist[v]) {
        dist[v] = nd
        prev[v] = u
        push(nd, v)
      }
    }
  }
  const wt = rg.ew[to.edge]
  const viaA = dist[ta] + to.t * wt
  const viaB = dist[tb] + (1 - to.t) * wt
  if (!Number.isFinite(Math.min(viaA, viaB))) return null
  let node = viaA <= viaB ? ta : tb
  const chain = []
  while (node !== -1) {
    chain.push([rg.x[node], rg.y[node]])
    node = prev[node]
  }
  chain.reverse()
  return {
    metres: from.perp + Math.min(viaA, viaB) + to.perp,
    points: [[from.x, from.y], lerp(from.edge, from.t), ...chain, lerp(to.edge, to.t), [to.x, to.y]],
  }
}

function pathLength(points) {
  let m = 0
  for (let k = 1; k < points.length; k++) m += Math.hypot(points[k][0] - points[k - 1][0], points[k][1] - points[k - 1][1])
  return m
}

/** Points every `step` metres along a polyline, excluding the start (an existing
 *  stop) and always ending at the last point; a regular stop closer than half a
 *  step to the end is dropped in favour of the end stop. */
export function placeStops(points, step) {
  const total = pathLength(points)
  const out = []
  const targets = []
  for (let c = step; c < total - step / 2; c += step) targets.push(c)
  targets.push(total)
  let acc = 0
  let k = 1
  for (const c of targets) {
    while (k < points.length) {
      const seg = Math.hypot(points[k][0] - points[k - 1][0], points[k][1] - points[k - 1][1])
      if (acc + seg >= c - 1e-6) {
        const t = seg > 0 ? (c - acc) / seg : 0
        out.push([points[k - 1][0] + (points[k][0] - points[k - 1][0]) * t, points[k - 1][1] + (points[k][1] - points[k - 1][1]) * t])
        break
      }
      acc += seg
      k++
    }
  }
  return out
}

/**
 * Median straight-line distance between consecutive CM stops in lk_metro's
 * published stop order (zero gaps of circular routes skipped). The OSRM line
 * geometry is not used: its one-way detours and loops run 25–50% longer than the
 * published route lengths.
 */
export function medianStopSpacing(metro, stops) {
  const byName = new Map(stops.map((s) => [s.name, s]))
  const gaps = []
  for (const f of metro.features.filter((x) => x.properties?.kind === 'line')) {
    const seq = String(f.properties.stops).split(' · ').map((n) => byName.get(n))
    if (seq.some((s) => !s)) throw new Error(`line ${f.properties.code} names an unknown stop`)
    for (let k = 1; k < seq.length; k++) {
      const d = Math.hypot(seq[k].x - seq[k - 1].x, seq[k].y - seq[k - 1].y)
      if (d > 0) gaps.push(d)
    }
  }
  gaps.sort((a, b) => a - b)
  return gaps[Math.floor(gaps.length / 2)]
}

