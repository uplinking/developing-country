/** GN adjacency: ≥ n vertices of one polygon within tol metres of the other's outline. */
export function adjacent(a, b, tol = GAP.adjacencyM, n = GAP.adjacencyVertices) {
  const [ax0, ay0, ax1, ay1] = a.bbox
  const [bx0, by0, bx1, by1] = b.bbox
  if (ax0 > bx1 + tol || bx0 > ax1 + tol || ay0 > by1 + tol || by0 > ay1 + tol) return false
  const t2 = tol * tol
  const near = (p, q) => {
    let hits = 0
    for (const ring of p.rings) {
      for (const [x, y] of ring) {
        if (x < q.bbox[0] - tol || x > q.bbox[2] + tol || y < q.bbox[1] - tol || y > q.bbox[3] + tol) continue
        let hit = false
        for (const r of q.rings) {
          for (let k = 0, l = r.length - 1; k < r.length; l = k++) {
            if (segFoot(x, y, r[l][0], r[l][1], r[k][0], r[k][1]).d2 <= t2) {
              hit = true
              break
            }
          }
          if (hit) break
        }
        if (hit && ++hits >= n) return true
      }
    }
    return false
  }
  return near(a, b) || near(b, a)
}

function components(ids, adj) {
  const seen = new Set()
  const out = []
  for (const id of ids) {
    if (seen.has(id)) continue
    const comp = []
    const stack = [id]
    seen.add(id)
    while (stack.length) {
      const u = stack.pop()
      comp.push(u)
      for (const v of adj.get(u) ?? []) {
        if (!seen.has(v) && ids.includes(v)) {
          seen.add(v)
          stack.push(v)
        }
      }
    }
    out.push(comp.sort((a, b) => a - b))
  }
  return out
}

