#!/usr/bin/env bun
// "Where Colombo's metro buses don't go" — gaps, duplication and illustrative
// candidate routes, derived from the same model as scripts/build-metro-coverage.mjs
// (walk graph, 80 m/min, 50 m frontage, 5 m raster, area-weighted GN population,
// Overture offices, OSM schools and hospitals). Writes:
//
//   public/data/metro-gap-clusters.geojson + .json   dense, unserved GN-division clusters
//   public/data/metro-stop-uniqueness.json           residents/offices only one stop reaches
//   public/data/metro-route-candidates.geojson + .json  illustrative links/extensions, marginal scores
//   public/data/metro-route-scenarios.json           current network vs network + best 3
//
// GAP CLUSTERS
//   Tier 1: GN divisions with density ≥ 10,000 residents/km² (about the top fifth of
//   study-area divisions; decile 9 starts near 9,800/km²) and < 10% of their area
//   within a 10-minute walk. Tier 2: ≥ 5,000/km² (about the study-area median) and
//   < 10%, forming clusters that contain no tier-1 division — the suburban gaps the
//   dense tier misses. Divisions are grouped when their gig-data polygons share a
//   boundary (≥ 2 vertices within 25 m of the other's outline, tolerant of the
//   digitising slivers between neighbours). Clusters with ≥ 15,000 residents beyond a
//   10-minute walk are kept.
//
// CANDIDATE ROUTES (illustrative, generated by rule — not recommendations)
//   For each gap cluster (largest unserved first), from its label point:
//     link       the nearest existing interchange stop (2+ CM routes) by road
//     extension  the nearest CM line terminus by road, when it differs from the
//                link's stop and is within 10 km by road
//   Routing follows OSM drivable main roads (trunk/primary/secondary/tertiary and
//   links), fetched once from Overpass (or a Geofabrik extract with osmium when
//   OSM_PBF is set) into the gitignored cache data/src/osm/. Candidate stops are
//   placed every median CM stop spacing (straight-line, consecutive stops). A
//   candidate's score is what it adds over the existing network: residents, offices,
//   schools and hospitals newly within 5/10 minutes, never double counted.
//
// Downloaded content is data only. Deterministic, validated, idempotent.
// Usage: bun scripts/build-metro-alternatives.mjs [--check]

