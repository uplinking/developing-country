export function validate({ clusterRows, uniqueRows, candidateRows, scenarioRows, network, studyPop, gndById, study, clusters }) {
  const problems = []
  const finite = (row, path) => {
    for (const [k, v] of Object.entries(row)) if (typeof v === 'number' && !Number.isFinite(v)) problems.push(`${path}.${k} not finite`)
  }
  ;[...clusterRows, ...uniqueRows, ...candidateRows, ...scenarioRows].forEach((r, i) => finite(r, `row${i}`))
  if (clusterRows.length < 3) problems.push(`only ${clusterRows.length} gap clusters`)
  const seen = new Set()
  for (const c of clusters) {
    for (const k of c.members) {
      if (seen.has(k)) problems.push(`GND ${study[k].id} in two clusters`)
      seen.add(k)
      if (!gndById.has(study[k].id)) problems.push(`unknown GND ${study[k].id}`)
    }
  }
  for (const r of clusterRows) {
    if (r.unserved_residents < GAP.minUnserved) problems.push(`${r.cluster_id} below the unserved floor`)
    if (r.unserved_residents > r.residents) problems.push(`${r.cluster_id} unserved > residents`)
  }
  let uniqueSum = 0
  for (const r of uniqueRows) {
    if (r.unique_pop_10min > r.pop_10min) problems.push(`${r.stop_id} unique > total`)
    if (r.unique_offices_10min > r.offices_10min) problems.push(`${r.stop_id} unique offices > total`)
    uniqueSum += r.unique_pop_10min
  }
  if (uniqueSum > network.stats[10].pop + uniqueRows.length) problems.push('unique residents exceed the network total')
  if (candidateRows.length < 4 || candidateRows.length > CANDIDATE.maxCandidates) problems.push(`${candidateRows.length} candidates`)
  for (const r of candidateRows) {
    if (r.new_pop_10min < 0 || r.new_pop_5min > r.new_pop_10min + 1) problems.push(`${r.candidate_id} bad new population`)
    if (!(r.length_km > 0) || r.stop_count < 1) problems.push(`${r.candidate_id} empty route`)
  }
  const [cur, best] = scenarioRows
  if (cur.residents_10min !== Math.round(network.stats[10].pop)) problems.push('current scenario differs from the network')
  const bestNew = candidateRows.filter((r) => r.in_best_3).reduce((a, r) => a + r.new_pop_10min, 0)
  if (best.residents_10min < cur.residents_10min) problems.push('best-3 scenario below current')
  if (best.residents_added_10min > bestNew + 3) problems.push('best-3 adds more than its candidates')
  if (cur.study_area_pop !== studyPop) problems.push('study population mismatch')
  if (problems.length) throw new Error(`build-metro-alternatives: validation failed\n  ${problems.join('\n  ')}`)
}

function serialize(path, value) {
  if (path.endsWith('.json')) parseIndicatorTable(value)
  return `${JSON.stringify(value)}\n`
}

async function main() {
  const check = process.argv.includes('--check')
  const { files } = await build()
  let changed = 0
  for (const [rel, value] of Object.entries(files)) {
    const text = serialize(rel, value)
    const path = join(ROOT, rel)
    const previous = existsSync(path) ? readFileSync(path, 'utf8') : null
    const kb = (Buffer.byteLength(text) / 1024).toFixed(0)
    if (previous === text) {
      console.log(`  unchanged ${rel} (${kb} KB)`)
      continue
    }
    changed++
    if (check) {
      console.error(`  stale ${rel}`)
      continue
    }
    writeFileSync(path, text)
    console.log(`  wrote ${rel} (${kb} KB)`)
  }
  if (check && changed) process.exit(1)
  console.log(changed ? `build-metro-alternatives: ${changed} file(s) updated` : 'build-metro-alternatives: unchanged (no-op)')
}

if (import.meta.main) {
  main().catch((e) => {
    console.error(e)
    process.exit(1)
  })
}
