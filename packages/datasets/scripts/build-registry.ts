import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { INDICATOR_DATASETS } from '../src/presets'

const outputPath = resolve(import.meta.dir, '../src/registry.generated.ts')

function quote(value: string): string {
  return JSON.stringify(value)
}

const ids = new Set<string>()
const rows = INDICATOR_DATASETS.map((dataset) => {
  if (ids.has(dataset.id)) throw new Error(`Duplicate indicator dataset ${dataset.id}`)
  ids.add(dataset.id)
  for (const [field, value] of Object.entries({
    id: dataset.id,
    title: dataset.title,
    label: dataset.label,
    description: dataset.description,
    vintage: dataset.vintage,
    ...dataset.note,
  })) {
    if (!value.trim() || value.includes('\n')) throw new Error(`Indicator dataset ${dataset.id} has an invalid ${field}`)
  }
  if (dataset.sourceIds.length === 0) throw new Error(`Indicator dataset ${dataset.id} needs at least one Source`)
  const firstPreset = dataset.presets[0]
  if (!firstPreset) throw new Error(`Indicator dataset ${dataset.id} needs a default chart preset`)
  return `  { id: ${quote(dataset.id)}, title: ${quote(dataset.title)}, label: ${quote(dataset.label)}, themeIds: ${JSON.stringify(dataset.themeIds)}, defaultPresetId: ${quote(firstPreset.id)} },`
})

const expected = [
  '// Generated by packages/datasets/scripts/build-registry.ts. Do not edit.',
  'export const GENERATED_INDICATOR_DATASET_REGISTRY = [',
  ...rows,
  '] as const',
  '',
].join('\n')

if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== expected) {
    console.error('Indicator dataset registry is stale. Run bun run datasets:sync.')
    process.exit(1)
  }
  console.log(`Indicator dataset registry is in sync (${INDICATOR_DATASETS.length}).`)
} else {
  writeFileSync(outputPath, expected)
  console.log(`Synced ${INDICATOR_DATASETS.length} indicator datasets into ${outputPath}.`)
}
